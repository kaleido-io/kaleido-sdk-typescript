// Generates src/schema.ts from swagger/subledger.yaml. With --check, exits
// non-zero when the committed file differs from a fresh generation.
import { readFileSync, writeFileSync } from "fs";
import openapiTS, { astToString } from "openapi-typescript";
import path from "path";
import ts from "typescript";
import { fileURLToPath, pathToFileURL } from "url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const swaggerFile = path.join(root, "swagger", "subledger.yaml");
const schemaFile = path.join(root, "src", "schema.ts");

const ANY = ts.factory.createKeywordTypeNode(ts.SyntaxKind.AnyKeyword);

const HEADER = readFileSync(path.join(root, "copyright.js"), "utf8").replace("<%= YEAR %>", "2026");

async function generate(): Promise<string> {
  const names: string[] = [];
  const ast = await openapiTS(pathToFileURL(swaggerFile), {
    transform(schemaObject, { path: schemaPath }) {
      const name = schemaPath?.match(/^#\/components\/schemas\/([^/]+)$/)?.[1];
      if (name) {
        names.push(name);
      }
      if (schemaObject.type === "object" && schemaObject.additionalProperties === true) {
        return ANY;
      }
      if (schemaObject.type === undefined && !("$ref" in schemaObject)) {
        return ANY;
      }
      return undefined;
    },
  });
  const aliases = [...new Set(names)]
    .sort()
    .map((n) => `export type ${n} = components["schemas"]["${n}"];`)
    .join("\n");
  return `${HEADER}\n// Generated by scripts/schema.ts from swagger/subledger.yaml. Do not edit.\n\n${astToString(ast)}\n${aliases}\n`;
}

const output = await generate();
if (process.argv.includes("--check")) {
  if (readFileSync(schemaFile, "utf8") !== output) {
    console.error("src/schema.ts is out of date with swagger/subledger.yaml: run `npm run schema`");
    process.exit(1);
  }
} else {
  writeFileSync(schemaFile, output);
}
